//! Measuring test selection against observed behaviour.
//!
//! The ground truth comes from *probes*: a function's body is made to
//! panic on entry, the repository's test suite is run, and the tests that
//! now fail (and passed before) are exactly the tests that executed the
//! function. The `codeatlas probe-tests` command produces a
//! [`TestGroundTruth`]; [`evaluate_tests`] compares it with the tests that
//! [`select_tests`] picks for the same function.
//!
//! Selection is meant to find tests that *could* be affected, so a test it
//! selects that does not execute the function in this run (a branch not
//! taken, another implementation behind the same trait) lowers precision
//! without being wrong in principle. A failing test it did not select is a
//! real miss.

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};

use crate::graph::impact::ImpactOptions;
use crate::graph::test_selection::select_tests;
use crate::graph::CodeGraph;
use crate::ingest::{fnv1a_extend, FNV1A_OFFSET};
use crate::model::SymbolId;
use crate::RepositoryAnalysis;

/// How the ground truth was obtained.
pub const PROBE_METHOD: &str = "panic-on-entry";
/// Prefix of tests that ran but have no symbol in the analysis (e.g.
/// generated by macros); written as `unmapped:<crate>::<path>`.
pub const UNMAPPED: &str = "unmapped:";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TestGroundTruth {
    pub repository: String,
    pub commit: Option<String>,
    /// [`source_hash`] of the analysed sources the probes were run on.
    pub source_hash: String,
    pub method: String,
    /// `rustc --version` of the run.
    pub toolchain: String,
    /// Every test that ran in the baseline, by symbol ID (or `unmapped:`).
    pub tests: Vec<String>,
    /// Tests failing without any probe; ignored in the probes.
    pub baseline_failures: Vec<String>,
    pub probes: Vec<Probe>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Probe {
    /// The function or method whose body panicked.
    pub symbol: String,
    pub status: ProbeStatus,
    /// Tests that failed with the probe and passed without it.
    pub failing: Vec<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProbeStatus {
    Ok,
    /// The probed code did not compile (e.g. used in a `const` context).
    BuildFailed,
    /// A test binary crashed or timed out, so some results are missing.
    Incomplete,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ProbeEvaluation {
    pub symbol: String,
    /// Tests that executed the symbol.
    pub actual: Vec<String>,
    /// Tests selected statically.
    pub predicted: Vec<String>,
    /// Executed but not selected.
    pub missed: Vec<String>,
    /// Selected but not executed.
    pub extra: Vec<String>,
    pub precision: Option<f64>,
    pub recall: Option<f64>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TestImpactSummary {
    /// Probes with a usable result.
    pub probes: u32,
    /// Probes that did not build or whose run was incomplete.
    pub skipped: u32,
    pub tests: u32,
    /// Tests without a symbol in the analysis (CodeAtlas cannot select them).
    pub unmapped_tests: u32,
    /// Summed over probes: tests that executed the symbol, tests selected,
    /// and tests both.
    pub actual: u32,
    pub predicted: u32,
    pub true_positives: u32,
    /// Micro-averaged over probes (`true_positives / predicted`).
    pub precision: Option<f64>,
    /// Micro-averaged (`true_positives / actual`).
    pub recall: Option<f64>,
    /// Recall counting only tests that have a symbol in the analysis.
    pub recall_known_tests: Option<f64>,
    /// Probes where selection and observation agree exactly.
    pub exact: u32,
    /// Probes whose symbol no test executed.
    pub not_executed: u32,
    /// ...of which selection also selected nothing.
    pub not_executed_and_not_selected: u32,
    /// Mean share of the suite selected / actually affected, per probe.
    pub mean_selected_share: f64,
    pub mean_actual_share: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TestImpactEvaluation {
    pub repository: String,
    pub commit: Option<String>,
    pub method: String,
    pub max_depth: u32,
    pub include_ambiguous: bool,
    pub summary: TestImpactSummary,
    pub probes: Vec<ProbeEvaluation>,
}

/// Compares static test selection with the ground truth, probe by probe.
pub fn evaluate_tests(
    graph: &CodeGraph,
    truth: &TestGroundTruth,
    options: ImpactOptions,
) -> TestImpactEvaluation {
    let total = truth.tests.len().max(1) as f64;
    let mut probes = Vec::new();
    let mut skipped = 0;
    for probe in &truth.probes {
        if probe.status != ProbeStatus::Ok {
            skipped += 1;
            continue;
        }
        let actual: BTreeSet<String> = probe.failing.iter().cloned().collect();
        let predicted: BTreeSet<String> = graph
            .node(&SymbolId::from_stored(probe.symbol.clone()))
            .and_then(|node| select_tests(graph, &[node], options).ok())
            .map(|selection| {
                let mut ids: BTreeSet<String> = selection
                    .to_run()
                    .into_iter()
                    .map(|id| id.to_string())
                    .collect();
                if options.include_ambiguous {
                    ids.extend(selection.possible.iter().map(|t| t.test.id.to_string()));
                }
                ids
            })
            .unwrap_or_default();
        let hits = actual.intersection(&predicted).count();
        probes.push(ProbeEvaluation {
            symbol: probe.symbol.clone(),
            missed: actual.difference(&predicted).cloned().collect(),
            extra: predicted.difference(&actual).cloned().collect(),
            precision: ratio(hits, predicted.len()),
            recall: ratio(hits, actual.len()),
            actual: actual.into_iter().collect(),
            predicted: predicted.into_iter().collect(),
        });
    }

    let sum = |f: &dyn Fn(&ProbeEvaluation) -> usize| probes.iter().map(f).sum::<usize>();
    let actual = sum(&|p| p.actual.len());
    let predicted = sum(&|p| p.predicted.len());
    let true_positives = sum(&|p| p.actual.len() - p.missed.len());
    let actual_known = sum(&|p| p.actual.iter().filter(|t| !t.starts_with(UNMAPPED)).count());
    let not_executed: Vec<&ProbeEvaluation> =
        probes.iter().filter(|p| p.actual.is_empty()).collect();
    let n = probes.len().max(1) as f64;
    let summary = TestImpactSummary {
        probes: probes.len() as u32,
        skipped,
        tests: truth.tests.len() as u32,
        unmapped_tests: truth
            .tests
            .iter()
            .filter(|t| t.starts_with(UNMAPPED))
            .count() as u32,
        actual: actual as u32,
        predicted: predicted as u32,
        true_positives: true_positives as u32,
        precision: ratio(true_positives, predicted),
        recall: ratio(true_positives, actual),
        recall_known_tests: ratio(true_positives, actual_known),
        exact: probes
            .iter()
            .filter(|p| p.missed.is_empty() && p.extra.is_empty())
            .count() as u32,
        not_executed: not_executed.len() as u32,
        not_executed_and_not_selected: not_executed
            .iter()
            .filter(|p| p.predicted.is_empty())
            .count() as u32,
        mean_selected_share: round(sum(&|p| p.predicted.len()) as f64 / total / n),
        mean_actual_share: round(actual as f64 / total / n),
    };
    TestImpactEvaluation {
        repository: truth.repository.clone(),
        commit: truth.commit.clone(),
        method: truth.method.clone(),
        max_depth: options.max_depth,
        include_ambiguous: options.include_ambiguous,
        summary,
        probes,
    }
}

/// A hash of every analysed file's path and content, to check that a
/// ground truth belongs to the sources being evaluated.
pub fn source_hash(analysis: &RepositoryAnalysis) -> String {
    let mut files: Vec<(&str, &str)> = analysis
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.content_hash.as_str()))
        .collect();
    files.sort_unstable();
    let mut hash = FNV1A_OFFSET;
    for (path, content) in files {
        for part in [path, "\0", content, "\n"] {
            hash = fnv1a_extend(hash, part.as_bytes());
        }
    }
    format!("{hash:016x}")
}

fn ratio(part: usize, whole: usize) -> Option<f64> {
    (whole > 0).then(|| round(part as f64 / whole as f64))
}

fn round(value: f64) -> f64 {
    (value * 1000.0).round() / 1000.0
}
